/** 折れ線 (y, x) の、高さ y での x */
function lineX(line, y) {
	if (y <= line[0][0]) return line[0][1];
	for (let i = 0; i + 1 < line.length; i++) {
		const [y0, x0] = line[i];
		const [y1, x1] = line[i + 1];
		if (y <= y1) return x0 + (x1 - x0) * (y - y0) / Math.max(y1 - y0, 1e-9);
	}
	return line[line.length - 1][1];
}
